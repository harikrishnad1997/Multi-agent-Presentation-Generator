"""Beamer LaTeX rendering and validation.

LaTeX is rendered deterministically from the structured Deck, NOT
generated by an LLM. That is a deliberate design choice: an LLM
writing raw LaTeX is where decks break (unescaped %, a missing
\\end{frame}, a \\note eaten by string handling).

The original repo's bug, fixed here and never reintroduced: it did
``text.replace('\\\\n', '\\n')`` on LLM output, which also rewrote the
``\\n`` inside ``\\note{...}`` into a newline + ``ote{...}``. This
module never does string-level newline replacement on LaTeX. Bullets
and notes are escaped as data, then placed into a fixed template.

Escaping order matters: backslash first, then the special chars.
"""
from __future__ import annotations

import re

from .models import Deck

_LATEX_SPECIALS = [
    ("\\", r"\textbackslash{}"),
    ("&", r"\&"),
    ("%", r"\%"),
    ("$", r"\$"),
    ("#", r"\#"),
    ("_", r"\_"),
    ("{", r"\{"),
    ("}", r"\}"),
    ("~", r"\textasciitilde{}"),
    ("^", r"\textasciicircum{}"),
]


def escape_latex(text: str) -> str:
    """Escape plain text so it is safe inside a LaTeX document."""
    out = str(text)
    for old, new in _LATEX_SPECIALS:
        out = out.replace(old, new)
    return out


def render_beamer(deck: Deck, author: str, institute: str, theme: str = "Madrid") -> str:
    """Render a Deck as a complete Beamer document."""
    lines: list[str] = [
        r"\documentclass{beamer}",
        rf"\usetheme{{{theme}}}",
        r"\usepackage{graphicx}",
        rf"\title{{{escape_latex(deck.title)}}}",
        rf"\author{{{escape_latex(author)}}}",
        rf"\institute{{{escape_latex(institute)}}}",
        r"\date{\today}",
        r"\begin{document}",
        "",
        r"\begin{frame}",
        r"  \titlepage",
        r"\end{frame}",
        "",
    ]
    for slide in sorted(deck.slides, key=lambda s: s.number):
        lines.append(rf"\begin{{frame}}{{{escape_latex(slide.title)}}}")
        lines.append(r"  \begin{itemize}")
        for bullet in slide.bullets:
            lines.append(rf"    \item {escape_latex(bullet)}")
        lines.append(r"  \end{itemize}")
        if slide.chart_file:
            lines.append(r"  \begin{center}")
            lines.append(rf"    \includegraphics[width=0.72\textwidth]{{{slide.chart_file}}}")
            if slide.chart and slide.chart.source_note:
                lines.append(rf"    \par \tiny{{{escape_latex(slide.chart.source_note)}}}")
            lines.append(r"  \end{center}")
        if slide.notes.strip():
            lines.append(rf"  \note{{{escape_latex(slide.notes)}}}")
        lines.append(r"\end{frame}")
        lines.append("")
    lines.append(r"\end{document}")
    return "\n".join(lines) + "\n"


def validate_latex(latex: str, expected_frames: int) -> list[str]:
    """Deterministic structural checks. Returns a list of problems (empty = ok)."""
    problems: list[str] = []
    if r"\begin{document}" not in latex or r"\end{document}" not in latex:
        problems.append("Missing \\begin{document} / \\end{document}.")
    for env in ("frame", "itemize", "document"):
        opens = len(re.findall(rf"\\begin\{{{env}\}}", latex))
        closes = len(re.findall(rf"\\end\{{{env}\}}", latex))
        if opens != closes:
            problems.append(f"Unbalanced {env}: {opens} opens, {closes} closes.")
    frames = len(re.findall(r"\\begin\{frame\}", latex))
    # +1 for the titlepage frame
    if frames != expected_frames + 1:
        problems.append(f"Expected {expected_frames + 1} frames (title + content), found {frames}.")
    # The original bug, caught explicitly: a \note that lost its backslash.
    if re.search(r"(?m)^ote\{", latex):
        problems.append("Found a bare 'ote{' — a \\note lost its backslash.")
    if re.search(r"(?m)^note\{", latex):
        problems.append("Found a bare 'note{' — a \\note lost its backslash.")
    return problems
